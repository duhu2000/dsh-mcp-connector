export function t(message, params) {
  const english = typeof document !== 'undefined' && /^en(?:-|$)/i.test(document.documentElement?.lang ?? '');
  const template = english && Object.hasOwn(EN, message) ? EN[message] : message;
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (token, key) => params?.[key] == null ? token : String(params[key]));
}
